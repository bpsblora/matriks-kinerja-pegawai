/* Firebase Spark account management — zero Cloud Functions.
 * Firebase Authentication Email/Password owns passwords; Firestore Rules own
 * access. An Admin can rename a login handle or rotate a Ketua Tim account
 * without ever reading the previous password.
 *
 * Every username resolves to an internal, opaque Firebase Auth email through
 * sparkRoleHandles. Profile, handle and old-session revocation are committed
 * together via a Firestore batch and verified again by Security Rules.
 * Historical Auth identities remain in Firebase Authentication (Spark Web SDK
 * cannot delete another user's Auth account), but their profile is inactive.
 */
import {initializeApp} from "firebase/app";
import {
 getAuth,signInWithEmailAndPassword,createUserWithEmailAndPassword,
 signOut,deleteUser,EmailAuthProvider,reauthenticateWithCredential,
 updatePassword
} from "firebase/auth";
import {
 getFirestore,collection,doc,getDoc,getDocs,updateDoc,writeBatch,serverTimestamp,onSnapshot
} from "firebase/firestore";
import {app,auth,db} from "./firebase/client.js";

const DOMAIN="roles.mkp-bps-blora.invalid";
const USERNAME=/^[a-z][a-z0-9._-]{2,31}$/;
const TEAM=/^[A-Z][0-9]{3}$/;
const ROLES=new Set(["admin","ketua_tim","kepala"]);
export const sparkRoleReady=import.meta.env.VITE_SPARK_ROLE_AUTH_READY==="true";
const roleApp=sparkRoleReady?initializeApp(app.options,"matriks-spark-role"):null;
const createApp=sparkRoleReady?initializeApp(app.options,"matriks-spark-account-creator"):null;
export const sparkRoleAuth=roleApp?getAuth(roleApp):null;
const creatorAuth=createApp?getAuth(createApp):null;
const roleDb=roleApp?getFirestore(roleApp):null;

export function normalizeSparkUsername(input){
 const name=String(input||"").trim().toLowerCase();
 if(!USERNAME.test(name))throw Error("Username harus 3–32 karakter: huruf kecil, angka, titik, _ atau -.");
 return name;
}
export function sparkLoginEmail(username){
 return normalizeSparkUsername(username)+"@"+DOMAIN;
}
function randomAlias(){
 // Opaque alias deliberately independent of mutable usernames.
 // The secure random UUID is generated by the browser Web Crypto API.
 const random=crypto.randomUUID().replace(/-/g,"").slice(0,24);
 return random+"@"+DOMAIN;
}
function validPassword(value){
 const size=new TextEncoder().encode(String(value||"")).length;
 if(size<12||size>72)throw Error("Password harus 12–72 byte.");
 return value;
}
function checkTeams(teamIds){
 if(!Array.isArray(teamIds)||!teamIds.length||teamIds.length>25)return false;
 return teamIds.every(id=>typeof id==="string"&&TEAM.test(id))&&new Set(teamIds).size===teamIds.length;
}
function validProfile(p,user){
 if(!p||p.active!==true||!ROLES.has(p.role)||typeof p.username!=="string"||!user)return null;
 const loginEmail=p.loginEmail||sparkLoginEmail(p.username); // bootstrap Admin compatibility
 if(loginEmail.toLowerCase()!==user.email?.toLowerCase())return null;
 const teamIds=Array.isArray(p.teamIds)?p.teamIds:[];
 if(p.role==="ketua_tim"&&(!checkTeams(teamIds)))return null;
 return {username:p.username,role:p.role,teamIds,active:true,uid:user.uid};
}
export async function getSparkRoleProfile(){
 if(!sparkRoleReady||!sparkRoleAuth?.currentUser)return null;
 const user=sparkRoleAuth.currentUser;
 const snap=await getDoc(doc(roleDb,"sparkRoleProfiles",user.uid));
 // Authentication and Firestore documents are independent. A successful
 // password sign-in must never be reported as an incorrect password merely
 // because the Firestore document ID differs by one character.
 if(!snap.exists())throw Error("SPARK_PROFILE_MISSING:"+user.uid);
 const data=snap.data();
 const profile=validProfile(data,user);
 if(profile)return profile;
 if(data.active!==true)throw Error("SPARK_PROFILE_INACTIVE:"+user.uid);
 if(data.role!=="admin"&&data.role!=="ketua_tim"&&data.role!=="kepala")
  throw Error("SPARK_PROFILE_ROLE_INVALID:"+user.uid);
 if(data.username!=="admin"&&user.email===sparkLoginEmail("admin"))
  throw Error("SPARK_PROFILE_USERNAME_INVALID:"+user.uid);
 const expectedEmail=data.loginEmail||sparkLoginEmail(data.username);
 if(expectedEmail.toLowerCase()!==user.email?.toLowerCase())
  throw Error("SPARK_PROFILE_EMAIL_MISMATCH:"+user.uid);
 throw Error("SPARK_PROFILE_INVALID:"+user.uid);
}
async function lookupRoleEmail(username){
 // The office Google viewer may resolve a login alias. No password is exposed.
 // Admin account before its handle is initialized uses the reserved bootstrap
 // alias; all newly created accounts require a Firestore handle.
 const name=normalizeSparkUsername(username);
 const office=auth.currentUser;
 if(!office)throw Error("Masuk dengan Google BPS Blora terlebih dahulu.");
 // The very first Admin is bootstrapped in Firebase Console and deliberately
 // has no sparkRoleHandles mapping. Check the fixed Admin alias BEFORE making
 // any Firestore lookup; deny-all Rules would otherwise block valid credentials.
 // Role privileges are granted only after reading the server-protected profile.
 if(name==="admin")return sparkLoginEmail(name);
 const snap=await getDoc(doc(db,"sparkRoleHandles",name));
 if(snap.exists()){
  const loginEmail=snap.data().authEmail;
  if(typeof loginEmail!=="string"||!loginEmail.endsWith("@"+DOMAIN))
   throw Error("Akun belum valid.");
  return loginEmail;
 }
 throw Error("Username tidak ditemukan. Hubungi Admin.");
}
export async function loginSparkRole(username,password){
 if(!sparkRoleReady||!sparkRoleAuth)throw Error("Aktifkan Email/Password dan aturan Spark di Firebase.");
 if(!password)throw Error("Masukkan password peran.");
 const loginEmail=await lookupRoleEmail(username);
 await signInWithEmailAndPassword(sparkRoleAuth,loginEmail,password);
 try{
  const profile=await getSparkRoleProfile();
  if(!profile||profile.username!==normalizeSparkUsername(username))
   throw Error("Akun tidak aktif atau belum diizinkan Admin.");
  return profile;
 }catch(e){
  await signOut(sparkRoleAuth).catch(()=>{});
  throw e;
 }
}
export async function restoreSparkRole(){
 if(!sparkRoleAuth?.currentUser)return null;
 try{
  const profile=await getSparkRoleProfile();
  if(!profile)await signOut(sparkRoleAuth);
  return profile;
 }catch{
  await signOut(sparkRoleAuth).catch(()=>{});
  return null;
 }
}
export async function logoutSparkRole(){
 if(sparkRoleAuth?.currentUser)await signOut(sparkRoleAuth);
}
export function watchSparkRoleRevocation(onRevoked){
 const user=sparkRoleAuth?.currentUser;
 if(!user)return ()=>{};
 // When Admin resets/deactivates a role, immediately end the role session
 // on other open tabs; no page reload is required.
 return onSnapshot(doc(roleDb,"sparkRoleProfiles",user.uid),snap=>{
  if(!snap.exists()||!validProfile(snap.data(),user))onRevoked();
 },()=>onRevoked());
}
async function requireAdmin(){
 const profile=await getSparkRoleProfile();
 if(!profile||profile.role!=="admin")throw Error("Hanya Admin aktif dapat mengelola akun.");
 return profile;
}
function handleDoc(name){return doc(roleDb,"sparkRoleHandles",name);}
function profileDoc(uid){return doc(roleDb,"sparkRoleProfiles",uid);}
function handleRecord(uid,authEmail,actorUid,createdAt=null){
 return {
  uid,authEmail,createdBy:actorUid,
  createdAt:createdAt||serverTimestamp(),updatedAt:serverTimestamp()
 };
}
export async function listSparkRoleAccounts(){
 await requireAdmin();
 const [profiles,handles]=await Promise.all([
  getDocs(collection(roleDb,"sparkRoleProfiles")),
  getDocs(collection(roleDb,"sparkRoleHandles"))
 ]);
 const currentUid=new Map(handles.docs.map(x=>[x.id,x.data().uid]));
 return profiles.docs
  .filter(x=>x.data().role==="admin" || currentUid.get(x.data().username)===x.id)
  .map(x=>({
   uid:x.id,username:x.data().username,role:x.data().role,
   teamIds:x.data().teamIds||[],active:x.data().active===true
  })).sort((a,b)=>a.username.localeCompare(b.username,"id"));
}
async function newRoleIdentity(password){
 if(!creatorAuth)throw Error("Autentikasi Spark belum siap.");
 const email=randomAlias();
 return createUserWithEmailAndPassword(creatorAuth,email,validPassword(password));
}
async function cleanupFailedIdentity(result){
 if(result?.user)await deleteUser(result.user).catch(()=>{});
 await signOut(creatorAuth).catch(()=>{});
}
export async function createSparkKetuaAccount({username,password,teamIds}){
 const actor=await requireAdmin();
 const name=normalizeSparkUsername(username);
 if(name==="admin")throw Error("Username admin dicadangkan.");
 if(!checkTeams(teamIds))throw Error("Pilih minimal satu tim yang valid.");
 validPassword(password);
 if((await getDoc(handleDoc(name))).exists())throw Error("Username sudah digunakan.");
 let registered=null;
 try{
  registered=await newRoleIdentity(password);
  const uid=registered.user.uid,mail=registered.user.email;
  const batch=writeBatch(roleDb);
  batch.set(profileDoc(uid),{
   username:name,loginEmail:mail,role:"ketua_tim",teamIds:[...teamIds],
   active:true,createdBy:actor.uid,createdAt:serverTimestamp(),updatedAt:serverTimestamp()
  });
  batch.set(handleDoc(name),handleRecord(uid,mail,actor.uid));
  await batch.commit();
  return {uid,username:name};
 }catch(e){
  await cleanupFailedIdentity(registered);
  throw e;
 }finally{await signOut(creatorAuth).catch(()=>{});}
}
export async function updateSparkAccount(uid,{username,teamIds,active}){
 const actor=await requireAdmin();
 if(!uid||uid===actor.uid)throw Error("Admin tidak dapat mengubah dirinya melalui menu ini.");
 const target=profileDoc(uid);
 const snap=await getDoc(target);
 if(!snap.exists()||snap.data().role!=="ketua_tim")throw Error("Hanya akun Ketua Tim yang dapat diubah.");
 const old=snap.data();
 const name=normalizeSparkUsername(username??old.username);
 if(!checkTeams(teamIds)||typeof active!=="boolean")throw Error("Tim atau status tidak valid.");
 const batch=writeBatch(roleDb);
 if(name!==old.username){
  if(name==="admin"||(await getDoc(handleDoc(name))).exists())throw Error("Username baru sudah digunakan.");
  const prev=await getDoc(handleDoc(old.username));
  if(!prev.exists()||prev.data().uid!==uid)throw Error("Identitas username lama tidak valid.");
  batch.set(handleDoc(name),handleRecord(uid,old.loginEmail,actor.uid));
  batch.delete(handleDoc(old.username));
 }
 batch.update(target,{username:name,teamIds:[...teamIds],active,updatedAt:serverTimestamp()});
 await batch.commit();
 return {username:name,uid};
}
export async function resetSparkAccountPassword(uid,newPassword){
 const actor=await requireAdmin();
 if(!uid||uid===actor.uid)throw Error("Admin tidak dapat mereset akunnya sendiri melalui menu ini.");
 const oldRef=profileDoc(uid),oldSnap=await getDoc(oldRef);
 if(!oldSnap.exists()||oldSnap.data().role!=="ketua_tim")throw Error("Hanya akun Ketua Tim yang dapat direset.");
 const old=oldSnap.data();
 if(old.active!==true)throw Error("Aktifkan akun dahulu sebelum mereset password.");
 const current=await getDoc(handleDoc(old.username));
 if(!current.exists()||current.data().uid!==uid)throw Error("Akun sudah diganti. Muat ulang daftar akun.");
 validPassword(newPassword);
 let replacement=null;
 try{
  replacement=await newRoleIdentity(newPassword);
  const newUid=replacement.user.uid,mail=replacement.user.email;
  const batch=writeBatch(roleDb);
  batch.set(profileDoc(newUid),{
   username:old.username,loginEmail:mail,role:"ketua_tim",
   teamIds:[...old.teamIds],active:old.active===true,
   createdBy:actor.uid,createdAt:serverTimestamp(),updatedAt:serverTimestamp()
  });
  batch.update(handleDoc(old.username),{uid:newUid,authEmail:mail,updatedAt:serverTimestamp()});
  batch.update(oldRef,{active:false,updatedAt:serverTimestamp()});
  await batch.commit();
  return {uid:newUid,username:old.username};
 }catch(e){
  await cleanupFailedIdentity(replacement);
  throw e;
 }finally{await signOut(creatorAuth).catch(()=>{});}
}
export async function changeSparkOwnPassword(currentPassword,newPassword){
 if(!sparkRoleAuth?.currentUser||!await getSparkRoleProfile())throw Error("Silakan login peran dahulu.");
 validPassword(newPassword);
 const user=sparkRoleAuth.currentUser;
 await reauthenticateWithCredential(user,EmailAuthProvider.credential(user.email,currentPassword));
 await updatePassword(user,newPassword);
 return true;
}
